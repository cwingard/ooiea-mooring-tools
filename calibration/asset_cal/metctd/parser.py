"""Calibration parsers for the METCTD instrument class (Sea-Bird SBE37 CT,
no pressure sensor -- part of the METBK surface meteorological buoy
package).

Ported from
tools/matlab/Endurance_cal_scripts/metctd/write_metctd_calcoeffs_to_csv.m,
rad_read_metctd_cal.m, and rad_read_metctd_cap.m.

METCTD is unlike every other class ported so far in two ways:

1. No series at all. The Matlab source never appends a series
   letter to the filename ("CGINS-METCTD-<sernum>__<caldate>.csv"),
   and there is no calibration/METCTD/ folder -- real files live
   inside calibration/METBKA/, the parent meteorological package's
   folder, alongside CGINS-METLGR-* files for a different
   sub-sensor entirely. write_csv's output_dir_name parameter (cli:
   --output-dir) must always be supplied for this class; the
   f"{class_code}{series}" default computes to "METCTDCAL" or
   "METCTDCAP", which does not exist.

2. Two deliberately distinct source formats, not two series. A
   vendor-supplied *.cal file and the QCT cap/log capture of what
   the vendor actually loaded onto the sensor should report the
   same coefficients but sometimes do not (human error on the
   vendor's side) -- so, by design, the operator states explicitly
   which source they're using rather than have it silently
   auto-detected by file extension (which is what the Matlab source
   actually does). MetctdCalParser and MetctdCapParser are
   registered under "METCTD-CAL" and "METCTD-CAP" respectively,
   reusing the existing CLASS-SERIES cli machinery unchanged: the
   second token is "CAL"/"CAP" rather than a physical series
   letter, which is why MetctdCal.series is documented as a source
   marker, not an instrument series.

Ported quirks:

- Coefficient values are preserved as exact strings from the source
  document (NOT reformatted, unlike OPTAA) -- confirmed against the
  real archive.
- Output is NOT alphabetized. The Matlab source's own
  alphabetical-reorder line is commented out for this class (unlike
  CTDBP/FLORT/PRESF/OPTAA, where it's active or the archive implies
  it); the real archive confirms plain insertion order
  (a0,a1,a2,a3,g,h,i,j,cpcor,ctcor,wbotc).
- The provenance note is pinned to CC_a0 (the first coefficient in
  that insertion order), matching the Matlab source and, for once,
  matching the archive exactly too -- no drift, unlike every other
  class checked so far.
- The serial column is "37-<sernum>" where sernum is the already
  5-char zero-padded string both readers produce internally. Matlab
  applies num2str to that already-formatted string with no format
  spec; this port treats that as a pass-through (i.e. the serial
  column keeps the leading zeros), which is the more defensible
  reading but is not independently confirmed -- no real archived
  example has a serial under 10000 that was generated by the
  current script (the one exception, serial 8028, was clearly
  generated by a different, older process entirely -- different
  serial-column style, different note format).
- rad_read_metctd_cal.m has an apparent bug: a coefficient it fails
  to find is assigned under the wrong (pre-rename) field name, which
  would silently produce an inconsistent struct rather than a clear
  error. This port does NOT replicate that -- a missing coefficient
  raises ValueError instead.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import ClassVar

from asset_cal.common.csv_writer import CalCoefficient, write_cal_csv
from asset_cal.common.series_parser import SeriesParser

_MONTHS = ("jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec")
_COEFFICIENT_ORDER = ("a0", "a1", "a2", "a3", "g", "h", "i", "j", "cpcor", "ctcor", "wbotc")

_CAL_COEFF_LABELS = ("TA0", "TA1", "TA2", "TA3", "CG", "CH", "CI", "CJ", "CPCOR", "CTCOR", "WBOTC")
_CAP_COEFF_TAGS = ("A0", "A1", "A2", "A3", "G", "H", "I", "J", "PCOR", "TCOR", "WBOTC")


@dataclass(frozen=True)
class MetctdCal:
    """Calibration coefficients parsed from a METCTD source document.

    Attributes
    ----------
    serial_number : str
        5-character zero-padded serial number string.
    series : str
        "CAL" or "CAP" -- NOT a physical instrument series; records
        which source document type this came from. See module
        docstring.
    caldate : str
        Calibration date as YYYYMMDD -- the latest of the
        temperature and conductivity sensor caldates.
    source_provenance : str
        Attached as the note on CC_a0 in the output csv.
    coefficients : dict[str, str]
        The 11 calibration coefficients (a0..a3, g, h, i, j, cpcor,
        ctcor, wbotc), exact strings as read from the source
        document, in insertion order -- output is not alphabetized
        for this class.
    """

    serial_number: str
    series: str
    caldate: str
    source_provenance: str
    coefficients: dict[str, str] = field(default_factory=dict)


class MetctdCalParser(SeriesParser[MetctdCal]):
    """Parses vendor-supplied SBE37 *.cal files."""

    class_code: ClassVar[str] = "METCTD"
    series: ClassVar[str] = "CAL"

    def parse(self, source_path: Path) -> MetctdCal:
        """Parse a METCTD *.cal file into a MetctdCal.

        UNVERIFIED -- no real .cal file was available; ported
        structurally from rad_read_metctd_cal.m.

        Raises
        ------
        ValueError
            If the serial number, either sensor caldate, or any
            coefficient cannot be found.
        """
        lines = [line.strip() for line in source_path.read_text(encoding="ascii").splitlines()]

        serial_number = _find_cal_serial_number(lines)
        temp_caldate = _find_cal_caldate(lines, "TCALDATE=")
        cond_caldate = _find_cal_caldate(lines, "CCALDATE=")
        caldate = max(_normalize_metctd_caldate(temp_caldate), _normalize_metctd_caldate(cond_caldate))

        coefficients = {
            output_name: _find_cal_coefficient(lines, label)
            for label, output_name in zip(_CAL_COEFF_LABELS, _COEFFICIENT_ORDER)
        }

        return MetctdCal(
            serial_number=serial_number,
            series=self.series,
            caldate=caldate,
            source_provenance=f"source: {source_path.name}",
            coefficients=coefficients,
        )

    def write_csv(
        self, cal: MetctdCal, calibration_root: Path, output_dir_name: str | None = None
    ) -> Path:
        return _write_metctd_csv(cal, calibration_root, output_dir_name, self.class_code, self.series)


class MetctdCapParser(SeriesParser[MetctdCal]):
    """Parses QCT cap/log captures (what the vendor loaded onto the sensor)."""

    class_code: ClassVar[str] = "METCTD"
    series: ClassVar[str] = "CAP"

    def parse(self, source_path: Path) -> MetctdCal:
        """Parse a METCTD QCT cap/log file into a MetctdCal.

        Ported from rad_read_metctd_cap.m. Tested against a real
        SBE37SM-RS485 QCT capture (serial 13471, cal 04-Jun-26);
        matches the vendor .cal file for the same calibration. The
        source filename is used only in the provenance note.

        Raises
        ------
        ValueError
            If the serial number, either sensor caldate, or any
            coefficient cannot be found.
        """
        lines = source_path.read_text(encoding="ascii").splitlines()

        serial_number = _find_cap_serial_number(lines)
        temp_caldate = _find_cap_sensor_caldate(lines, "TEMP1")
        cond_caldate = _find_cap_sensor_caldate(lines, "WBCOND0")
        if temp_caldate is None or cond_caldate is None:
            raise ValueError("Could not find a caldate for one or both METCTD sensors (TEMP1/WBCOND0).")
        caldate = max(_normalize_metctd_caldate(temp_caldate), _normalize_metctd_caldate(cond_caldate))

        coefficients = {
            output_name: _find_cap_coefficient(lines, tag)
            for tag, output_name in zip(_CAP_COEFF_TAGS, _COEFFICIENT_ORDER)
        }

        return MetctdCal(
            serial_number=serial_number,
            series=self.series,
            caldate=caldate,
            source_provenance=f"source: {source_path.name}",
            coefficients=coefficients,
        )

    def write_csv(
        self, cal: MetctdCal, calibration_root: Path, output_dir_name: str | None = None
    ) -> Path:
        return _write_metctd_csv(cal, calibration_root, output_dir_name, self.class_code, self.series)


def _write_metctd_csv(
    cal: MetctdCal, calibration_root: Path, output_dir_name: str | None, class_code: str, series: str
) -> Path:
    folder_name = output_dir_name if output_dir_name is not None else f"{class_code}{series}"
    output_dir = calibration_root / folder_name
    if not output_dir.is_dir():
        raise FileNotFoundError(
            f"Expected existing directory {output_dir}; METCTD has no folder of its own -- "
            "pass output_dir_name (cli: --output-dir) pointing at the correct one, e.g. METBKA."
        )

    filename = f"CGINS-{class_code}-{cal.serial_number}__{cal.caldate}.csv"
    output_path = output_dir / filename

    serial_column = f"37-{cal.serial_number}"
    coefficients = [CalCoefficient(f"CC_{name}", cal.coefficients[name]) for name in _COEFFICIENT_ORDER]
    first = coefficients[0]
    coefficients[0] = CalCoefficient(first.name, first.value, cal.source_provenance)

    return write_cal_csv(output_path, serial_column, coefficients)


def _find_cal_serial_number(lines: list[str]) -> str:
    for line in lines:
        if "SERIALNO=" in line:
            after = line.split("NO=", 1)[1]
            match = re.match(r"\s*(\d+)", after)
            if match:
                return f"{int(match.group(1)):05d}"
            raise ValueError(f"Could not parse serial number from line: {line!r}")
    raise ValueError("Could not find 'SERIALNO=' line in cal file.")


def _find_cal_caldate(lines: list[str], match: str) -> str:
    for line in lines:
        if match in line:
            return line.split("=", 1)[1].strip()
    raise ValueError(f"Could not find {match!r} line in cal file.")


def _find_cal_coefficient(lines: list[str], label: str) -> str:
    label_pattern = f"{label}="
    matches = [line for line in lines if line.startswith(label_pattern)]
    if not matches:
        raise ValueError(f"Could not find coefficient labeled {label!r} in cal file.")
    return matches[-1][len(label_pattern):].strip()


def _find_cap_serial_number(lines: list[str]) -> str:
    marker = "SERIAL NO. "
    for line in lines:
        if marker in line:
            idx = line.find(marker) + len(marker)
            raw = line[idx: idx + 5]
            if raw.endswith(" "):
                raw = "0" + raw[:4]
            return raw
    raise ValueError("Could not find 'SERIAL NO. ' line in cap file.")


def _extract_xml_value(line: str) -> str:
    first_gt = line.find(">")
    second_lt = line.find("<", first_gt + 1) if first_gt != -1 else -1
    if first_gt == -1 or second_lt == -1:
        raise ValueError(f"Could not parse xml-style value from line: {line!r}")
    return line[first_gt + 1: second_lt].strip()


def _find_cap_sensor_caldate(lines: list[str], sensor_tag: str) -> str | None:
    for i, line in enumerate(lines):
        if sensor_tag in line and i + 2 < len(lines):
            return _extract_xml_value(lines[i + 2])
    return None


def _find_cap_coefficient(lines: list[str], tag: str) -> str:
    open_tag = f"<{tag}>"
    matches = [line for line in lines if open_tag in line]
    if not matches:
        raise ValueError(f"Could not find coefficient tag {open_tag!r} in cap file.")
    return _extract_xml_value(matches[0])


def _normalize_metctd_caldate(date_str: str) -> str:
    """Convert a 'dd-mmm-yy' caldate (e.g. '17-jul-13') to YYYYMMDD."""
    if len(date_str) < 9:
        raise ValueError(f"Unexpected caldate format: {date_str!r}")
    day = date_str[0:2]
    month_abbr = date_str[3:6].lower()
    year_suffix = date_str[7:9]
    if month_abbr not in _MONTHS:
        raise ValueError(f"Unrecognized month abbreviation in caldate: {date_str!r}")
    month_num = _MONTHS.index(month_abbr) + 1
    return f"20{year_suffix}{month_num:02d}{day}"
